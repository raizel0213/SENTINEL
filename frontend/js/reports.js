/* SENTINEL — reports & exports.
   Saved scans (with an id) export via the backend report generator.
   Unsaved/offline records fall back to local JSON/CSV builders ported from
   SENTINEL 1.x. Markdown/HTML require the local API. */
(() => {
  'use strict';

  const SENTINEL = (window.SENTINEL = window.SENTINEL || {});
  const $ = (s) => document.querySelector(s);

  const LOCAL_WEIGHTS = { Critical: 25, High: 15, Medium: 8, Low: 3, Info: 0, Pass: 0 };
  const SCORE_MODEL_TEXT = '100 minus 25 per Critical, 15 per High, 8 per Medium, 3 per Low; '
    + 'clamped to 0-100. Educational heuristic.';

  /* --- offline helpers ------------------------------------------------------- */

  /** Attach score/grade/counts to a browser-mode result when the API is down. */
  function attachLocalScore(result) {
    if (result.mode === 'browser' || result.score_applicable === false) {
      result.score_applicable = false;
      result.score = null;
      result.grade = null;
      return result;
    }
    const score = Math.max(0, Math.min(100, 100 - result.checks.reduce(
      (sum, c) => sum + (LOCAL_WEIGHTS[c.severity] || 0), 0)));
    const bands = [[95, 'A+'], [85, 'A'], [70, 'B'], [55, 'C'], [40, 'D'], [0, 'F']];
    result.score_applicable = true;
    result.score = score;
    result.grade = (bands.find(([floor]) => score >= floor) || [0, 'F'])[1];
    return result;
  }

  function download(name, content, type) {
    const blob = new Blob([content], { type });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = name;
    document.body.append(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  function csvEscape(value) {
    let text = String(value ?? '');
    // CSV quoting does not prevent spreadsheet formula execution. Prefix a
    // literal apostrophe when a formula trigger is the first meaningful char.
    if (/^[\s\x00-\x1f]*[=+\-@]/.test(text)) text = "'" + text;
    return '"' + text.replace(/"/g, '""') + '"';
  }

  function localReportObject(record) {
    return {
      product: 'SENTINEL',
      version: '2.5.0',
      target: record.target,
      mode: record.mode,
      modeLabel: record.modeLabel,
      timestamp: record.timestamp,
      httpStatus: record.status,
      durationMs: record.duration,
      score: record.score,
      grade: record.grade,
      scoreModel: record.mode === 'browser' ? 'Not applicable: CORS-filtered browser visibility cannot support a reliable score.' : SCORE_MODEL_TEXT,
      observedHeadersCount: record.observed,
      findings: record.checks,
      limitations: record.limitations || [],
    };
  }

  /* --- export actions ---------------------------------------------------------- */

  function triggerDownload(url) {
    const a = document.createElement('a');
    a.href = url;
    document.body.append(a);
    a.click();
    a.remove();
  }

  function exportScan(format) {
    const record = SENTINEL.app.state.current;
    if (!record) {
      SENTINEL.app.toast('No scan loaded — run an analysis first.');
      return;
    }
    const stamp = new Date().toISOString().slice(0, 10);
    if (record.id && SENTINEL.app.state.apiOnline) {
      triggerDownload(SENTINEL.api.reportUrl(record.id, format));
      SENTINEL.app.toast(format.toUpperCase() + ' report exported.');
      return;
    }
    if (format === 'json') {
      download('sentinel-report-' + stamp + '.json',
        JSON.stringify(localReportObject(record), null, 2), 'application/json');
      SENTINEL.app.toast('JSON report exported (local copy).');
      return;
    }
    if (format === 'csv') {
      const keys = ['id', 'severity', 'outcome', 'name', 'header', 'status', 'evidence', 'description', 'impact', 'fix', 'docs'];
      const lines = [keys.join(','),
        ...record.checks.map((c) => keys.map((k) => csvEscape(c[k])).join(','))];
      download('sentinel-findings-' + stamp + '.csv',
        '\ufeff' + lines.join('\r\n'), 'text/csv;charset=utf-8');
      SENTINEL.app.toast('CSV findings exported (local copy).');
      return;
    }
    SENTINEL.app.toast('Markdown and HTML reports are generated by the local API — start the backend.');
  }

  function printReport() {
    const record = SENTINEL.app.state.current;
    if (record && record.id && SENTINEL.app.state.apiOnline) {
      window.open(SENTINEL.api.reportUrl(record.id, 'html'), '_blank', 'noopener,noreferrer');
      return;
    }
    SENTINEL.app.toast('The printable report needs a saved scan and the local API — using browser print.');
    window.print();
  }

  function bind() {
    $('#exportJson').addEventListener('click', () => exportScan('json'));
    $('#exportJsonTop').addEventListener('click', () => exportScan('json'));
    $('#exportCsv').addEventListener('click', () => exportScan('csv'));
    $('#exportCsv2').addEventListener('click', () => exportScan('csv'));
    $('#exportMd').addEventListener('click', () => exportScan('md'));
    $('#printReport').addEventListener('click', printReport);
  }

  SENTINEL.reports = { exportScan, printReport, attachLocalScore, bind, localReportObject };
})();
